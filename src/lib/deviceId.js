/**
 * deviceId.js
 * توليد وحفظ مُعرّف ثابت للجهاز/المتصفح، مستخدم لربط حساب الطالب بجهاز واحد.
 *
 * ملاحظة مهمة: مفيش API في المتصفح بيدي "هوية جهاز" حقيقية — أقرب حاجة عملية
 * ومستقرة هي UUID بنولّده مرة واحدة ونخزّنه في localStorage. طول ما المستخدم
 * مغيرش المتصفح أو عمل مسح لبيانات الموقع أو فورمات للجهاز، القيمة دي بتفضل
 * ثابتة. لو حصل أي من دول، هيتولد UUID جديد — وده بالظبط السلوك المطلوب
 * (جهاز/متصفح جديد لازم يحتاج Reset من المدرس).
 */

import { safeLocalStorage } from '@/lib/safe-storage';

const DEVICE_ID_KEY = 'khatwa_device_id';

function generateUUID() {
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') {
    return crypto.randomUUID();
  }
  // Fallback لمتصفحات قديمة جداً مش داعمة crypto.randomUUID
  return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, (c) => {
    const r = (Math.random() * 16) | 0;
    const v = c === 'x' ? r : (r & 0x3) | 0x8;
    return v.toString(16);
  });
}

// ── BUGFIX (device-restriction false positives: "هذا الحساب مرتبط بجهاز آخر") ──
// المشكلة القديمة: الكود كان بيتولّد UUID عشوائي ويحاول يخزّنه في
// localStorage، من غير ما يتحقق إن التخزين نجح فعلاً. safeLocalStorage.setItem
// مصمّم عمدًا إنه "يبلع" أي خطأ (Private/Incognito Mode، متصفحات مدمجة في
// أجهزة/سبورات ذكية مقيّدة، أو أي قيود تخزين) ويرجّع false بصمت — لكن
// getDeviceId() القديمة ماكانتش بتتحقق من القيمة المُرجعة دي خالص. النتيجة:
// في أي بيئة بيفشل فيها التخزين، كان بيتولّد UUID عشوائي جديد تمامًا في *كل*
// استدعاء — حتى على نفس الجهاز الفعلي بالظبط، وحتى بين نداءين متتاليين في
// نفس الجلسة (مثلًا وقت تفعيل البصمة: register/options ثم register/verify) —
// فالسيرفر كان بيرفض الدخول كـ"جهاز آخر" رغم إنه نفس الجهاز فعليًا.
//
// الإصلاح (بدون أي تغيير في قاعدة "جهاز واحد لكل حساب" نفسها):
//   1) لو localStorage متاح وموثوق فعلاً (بنتحقق بالكتابة ثم القراءة الفورية
//      للتأكد إن القيمة رجعت زي ما اتخزنت بالظبط، مش بس الاعتماد على عدم
//      حدوث Exception) → يفضل هو المصدر الوحيد المعتمد، لأنه الوحيد اللي
//      بيثبت القيمة فعليًا عبر إغلاق/فتح المتصفح — بدون أي تغيير هنا.
//   2) لو مش متاح/مش موثوق → *لا* نولّد UUID جديد في كل مرة (ده كان أصل
//      المشكلة)، لكن كمان *لا* نستخدم أي "بديل" يعتمد على معلومات قابلة
//      للتكرار بين أجهزة مختلفة (زي User-Agent أو أي بصمة متصفح) — أي قيمة
//      زي دي ممكن تتطابق بسهولة بين جهازين مختلفين فعلًا (نفس المتصفح/
//      الإصدار)، وده هيضعف قاعدة "جهاز واحد لكل حساب" فعليًا، وهذا مرفوض
//      صراحة. بدل كده، بنحتفظ بنسخة واحدة في متغيّر بالذاكرة (module-level)
//      طول عمر تحميل الصفحة الحالي بس — فأي نداءات API متتالية في نفس
//      الجلسة (تسجيل الدخول، تفعيل/استخدام البصمة، إلخ) تبعت *نفس* القيمة
//      بدل قيم عشوائية مختلفة في كل نداء. ده بيمنع أسوأ سيناريو (اختلاف
//      الـID داخل نفس الجلسة الواحدة)، لكنه صراحة *مش* حل كامل لعدم ثبات
//      التخزين نفسه عبر إعادة تحميل الصفحة — مفيش حل من جهة الـFrontend وحده
//      يقدر يضمن ده لو التخزين فعليًا مش شغال في هذا المتصفح تحديدًا.
let memoryFallbackId = null;

export function getDeviceId() {
  if (safeLocalStorage.isAvailable()) {
    let id = safeLocalStorage.getItem(DEVICE_ID_KEY);
    if (!id) {
      id = generateUUID();
      safeLocalStorage.setItem(DEVICE_ID_KEY, id);
    }
    // تحقق فوري إن القيمة اتخزنت واترجعت فعلاً زي ما هي (وليس فقط أن
    // setItem لم يرمِ خطأ) — يغطي حالات نادرة يكون فيها التخزين "متاح"
    // شكليًا لكن غير موثوق فعليًا.
    if (safeLocalStorage.getItem(DEVICE_ID_KEY) === id) return id;
  }

  // localStorage مش متاح أو مش موثوق في هذا المتصفح — نستخدم/نولّد قيمة
  // واحدة ثابتة في الذاكرة طول عمر تحميل الصفحة الحالي، بدل توليد قيمة
  // عشوائية جديدة في كل استدعاء.
  if (!memoryFallbackId) memoryFallbackId = generateUUID();
  return memoryFallbackId;
}